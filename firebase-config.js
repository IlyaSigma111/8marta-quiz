// Функция для перемешивания массива
window.shuffleArray = function(array) {
    const newArray = [...array];
    for (let i = newArray.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [newArray[i], newArray[j]] = [newArray[j], newArray[i]];
    }
    return newArray;
};

// Функция для получения перемешанных вариантов ответа
window.getShuffledOptions = function(question) {
    // Правильный ответ (текст)
    const correctText = question.options[question.correct];
    
    // Создаём массив объектов
    const optionsWithMeta = question.options.map((text, index) => ({
        text: text,
        isCorrect: index === question.correct
    }));
    
    // Перемешиваем
    const shuffled = window.shuffleArray(optionsWithMeta);
    
    // Находим новый индекс правильного ответа
    const newCorrectIndex = shuffled.findIndex(item => item.isCorrect);
    
    return {
        options: shuffled.map(item => item.text),
        correct: newCorrectIndex,
        originalCorrectText: correctText
    };
};

